"""Write a short monthly report from the processed data.

    python monthly_report.py            # writes reports/<YYYY-MM>.md and prints it

GitHub Actions runs this after the monthly refresh and posts the report as an
issue, so the repo owner gets it by email / GitHub notification every month.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "src"))

from euro_markets import quality  # noqa: E402

PROCESSED = ROOT / "data" / "processed"
REPORTS = ROOT / "reports"

ROWS = [
    ("dfr", "ECB deposit rate", "%", 2),
    ("estr", "€STR", "%", 2),
    ("euribor3m", "Euribor 3M", "%", 2),
    ("hicp", "HICP inflation (YoY)", "%", 1),
    ("real_dfr", "Real deposit rate", "%", 2),
    ("de10y", "Bund 10Y", "%", 2),
    ("spread_2s10s", "2s10s slope", "bps", 0),
    ("spread_btp_bund", "BTP-Bund", "bps", 0),
    ("spread_oat_bund", "OAT-Bund", "bps", 0),
    ("spread_bono_bund", "Bono-Bund", "bps", 0),
    ("eurusd", "EUR/USD", "", 4),
    ("eurinr", "EUR/INR", "", 2),
    ("sx5e", "EURO STOXX 50", "", 0),
]


def load_wide() -> pd.DataFrame:
    fact = pd.read_csv(PROCESSED / "fact_market_monthly.csv")
    dates = pd.read_csv(PROCESSED / "dim_date.csv", parse_dates=["month_start"])
    fact = fact.merge(dates[["date_key", "month_start"]], on="date_key")
    return fact.pivot_table(index="month_start", columns="series_id", values="value").sort_index()


def policy_stance(dfr: pd.Series) -> str:
    s = dfr.dropna()
    if len(s) < 2:
        return "n/a"
    chg = s.iloc[-1] - s.iloc[-2]
    return "Hiking" if chg > 0 else "Cutting" if chg < 0 else "On hold"


def curve_status(slope_bps: float) -> str:
    return "Inverted" if slope_bps < 0 else "Flat" if slope_bps < 50 else "Steep"


def fmt(v: float, dec: int, unit: str) -> str:
    if pd.isna(v):
        return "–"
    return f"{v:,.{dec}f}{(' ' + unit) if unit else ''}"


def build_report(wide: pd.DataFrame) -> tuple[str, str]:
    month = wide.index.max()
    title = f"ECB monthly report – {month:%b %Y}"

    lines = [f"# {title}", ""]
    dfr = wide["dfr"].dropna()
    slope = wide["spread_2s10s"].dropna()
    lines += [
        f"**Policy stance:** {policy_stance(dfr)} (deposit rate {dfr.iloc[-1]:.2f}%)  ",
        f"**Curve:** {curve_status(slope.iloc[-1])} (2s10s {slope.iloc[-1]:.0f} bps)",
        "",
        "| Series | Latest month | Value | Change vs prev. month |",
        "|---|---|---|---|",
    ]
    for sid, name, unit, dec in ROWS:
        if sid not in wide:
            continue
        s = wide[sid].dropna()
        if s.empty:
            continue
        chg = s.iloc[-1] - s.iloc[-2] if len(s) > 1 else float("nan")
        sign = "+" if chg > 0 else ""
        chg_txt = "–" if pd.isna(chg) else f"{sign}{chg:,.{dec}f}{(' ' + unit) if unit else ''}"
        stale = " ⚠️" if s.index.max() < month else ""
        lines.append(f"| {name} | {s.index.max():%b %Y}{stale} | {fmt(s.iloc[-1], dec, unit)} | {chg_txt} |")

    raw_cols = [c for c in quality.BOUNDS if c in wide]
    issues = quality.run_checks(wide[raw_cols], max_stale_months=1)
    lines += ["", "## Data quality"]
    lines += [f"- ⚠️ {i}" for i in issues] if issues else ["- ✅ All checks passed – every series is up to date."]
    lines += ["", "_Auto-generated by GitHub Actions after the monthly ECB refresh._"]
    return title, "\n".join(lines) + "\n"


def main() -> int:
    wide = load_wide()
    title, body = build_report(wide)
    REPORTS.mkdir(exist_ok=True)
    path = REPORTS / f"{wide.index.max():%Y-%m}.md"
    path.write_text(body, encoding="utf-8")
    (REPORTS / "latest_title.txt").write_text(title, encoding="utf-8")
    print(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
